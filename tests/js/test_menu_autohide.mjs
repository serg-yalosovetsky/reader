import assert from 'node:assert/strict'
import { MENU_HIDE_MS, menuAutohideEnabled, shouldRevealMenu } from '../../frontend/js/core/menu-autohide.js'
assert.equal(MENU_HIDE_MS, 5000)
assert.equal(menuAutohideEnabled('pdf'), true)
assert.equal(menuAutohideEnabled('epub'), false)
assert.equal(menuAutohideEnabled('epub', { menuAutohidePdf: true }), false)
assert.equal(menuAutohideEnabled('pdf', { menuAutohidePdf: false }), false)
assert.equal(menuAutohideEnabled('fb2', { menuAutohideOther: true }), true)
for (const key of ['ArrowLeft', 'ArrowRight', 'PageUp', 'PageDown', ' ', 'Enter', 'Home', 'End'])
  assert.equal(shouldRevealMenu({ type: 'keydown', key }), false)
for (const type of ['wheel', 'touchstart', 'touchend', 'swipe', 'pointerdown'])
  assert.equal(shouldRevealMenu({ type }), false)
for (const key of ['Tab', 'Escape']) assert.equal(shouldRevealMenu({ type: 'keydown', key }), true)
assert.equal(shouldRevealMenu({ type: 'click', center: true }), true)
assert.equal(shouldRevealMenu({ type: 'click', center: false }), false)
for (const y of [0, 40, 760, 800])
  assert.equal(shouldRevealMenu({ type: 'pointermove', mouse: true, y, height: 800 }), true)
assert.equal(shouldRevealMenu({ type: 'pointermove', mouse: true, y: 400, height: 800 }), false)
assert.equal(shouldRevealMenu({ type: 'pointermove', mouse: false, y: 0, height: 800 }), false)
assert.equal(shouldRevealMenu({ type: 'focusin', panel: true }), true)
assert.equal(shouldRevealMenu({ type: 'focusin', panel: false }), false)
console.log('ok: menu autohide')
